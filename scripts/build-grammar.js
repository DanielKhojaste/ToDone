#!/usr/bin/env node
/*
 * Generates syntaxes/todone.tmLanguage.json.
 *
 * The grammar is a port of ToDone.tmLanguage from ToDone for Sublime Text
 * (https://github.com/tiffon/sublime-to-done), Copyright (c) 2013 Edward Joseph
 * Farro, MIT License. See THIRD_PARTY_NOTICES.md.
 *
 * The five priority levels repeat the same structure, so the grammar is built
 * from this script instead of being maintained by hand. Run `npm run grammar`
 * after editing and commit both files. A test checks they stay in sync.
 *
 * Scope naming
 * ------------
 * Each token gets one or more widely supported "fallback" scopes (comment,
 * markup.heading, keyword.control, ...) so that ToDone files look reasonable in
 * any color theme, followed by a ToDone-specific `meta.*.todone` scope last.
 * VS Code resolves the innermost scope first, so a rule written for the
 * specific scope (for example `meta.title.priority-5.todone`) always wins over
 * the fallback.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const LEVELS = [5, 4, 3, 2, 1];

/**
 * Fallback scopes for task titles. They were picked by rendering the fixtures
 * with the built-in Dark Modern, Light Modern, Monokai, Solarized, Quiet Light
 * and High Contrast themes so that the five levels stay distinct from each
 * other and from notes (which use `comment`).
 */
const TITLE_FALLBACK = {
  1: '',
  2: 'support.type',
  3: 'keyword.control',
  4: 'entity.name.function',
  5: 'invalid.illegal strong',
};

/** Fallback scopes for the priority marker (`-3`, `---`). */
const MARKER_FALLBACK = {
  1: 'punctuation.definition.list.begin.markdown',
  2: 'punctuation.definition.list.begin.markdown',
  3: 'punctuation.definition.list.begin.markdown',
  4: 'punctuation.definition.list.begin.markdown',
  5: 'invalid.illegal strong',
};

const scope = (...parts) => [...new Set(parts.join(' ').split(' ').filter(Boolean))].join(' ');

// Task title: everything up to an inline note (`:`) or raw note (`///`).
// `://` is allowed so URLs survive inside titles, as in the original grammar.
const TITLE = '((?:://|/(?!//)|[^:\\n/])*)';

// A priority marker for level n: n hyphens or one hyphen followed by the digit.
const marker = (n) => `(-{${n}}|-(${n}))(?=\\s)`;

// A block (task and everything nested under it) ends at the first line with
// content that is not indented deeper than the task. Blank lines do not end a
// block. See "Known differences" in the README.
const BLOCK_END = '^(?=[ \\t]*\\S)(?!\\1[ \\t])';

function activeTask(n) {
  return {
    name: `meta.task.priority-${n}.todone`,
    begin: `^([ \\t]*)${marker(n)}([ \\t]*)${TITLE}`,
    beginCaptures: {
      2: { name: scope(MARKER_FALLBACK[n], `meta.marker.priority-${n}.todone`) },
      3: { name: 'meta.marker.numeral.todone' },
      5: {
        name: scope(TITLE_FALLBACK[n], `meta.title.priority-${n}.todone`),
        patterns: [{ include: '#emphasis' }],
      },
    },
    end: BLOCK_END,
    patterns: [{ include: '#block-content' }],
  };
}

function emergencyTask(n) {
  return {
    name: `meta.task.emergency.priority-${n}.todone`,
    begin: `^([ \\t]*)(!)${marker(n)}([ \\t]*)${TITLE}`,
    beginCaptures: {
      2: { name: 'invalid.illegal strong meta.state.emergency.todone' },
      3: { name: scope(MARKER_FALLBACK[n], `meta.marker.priority-${n}.todone`) },
      4: { name: 'meta.marker.numeral.todone' },
      6: {
        name: scope(TITLE_FALLBACK[n], 'strong', `meta.title.priority-${n}.emergency.todone`),
        patterns: [{ include: '#emphasis' }],
      },
    },
    end: BLOCK_END,
    patterns: [{ include: '#block-content' }],
  };
}

const grammar = {
  $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
  information_for_contributors: [
    'This file is generated by scripts/build-grammar.js. Edit that script instead.',
    'Ported from ToDone for Sublime Text by tiffon (https://github.com/tiffon/sublime-to-done), MIT License.',
  ],
  name: 'ToDone',
  scopeName: 'text.todone',
  fileTypes: ['todo', 'todone'],
  patterns: [{ include: '#block-content' }],
  repository: {
    'block-content': {
      patterns: [
        { include: '#completed-task' },
        { include: '#cancelled-task' },
        { include: '#heading' },
        ...LEVELS.map((n) => ({ include: `#emergency-task-${n}` })),
        ...LEVELS.map((n) => ({ include: `#task-${n}` })),
        { include: '#note' },
      ],
    },

    // Unindented lines that are not tasks are headings (the original calls
    // them task classes). Text between `/*` and `*/` is an offset heading.
    heading: {
      patterns: [
        {
          name: 'markup.heading meta.heading.block.todone',
          begin: '^(/\\*)',
          beginCaptures: { 1: { name: 'comment punctuation.definition.heading.begin.todone' } },
          end: '(\\*/)',
          endCaptures: { 1: { name: 'comment punctuation.definition.heading.end.todone' } },
        },
        {
          name: 'markup.heading meta.heading.todone',
          match: '^[^\\s.\\-+!].*$',
        },
      ],
    },

    // `+` marks a task as completed. Everything nested under it is dimmed.
    'completed-task': {
      name: 'comment meta.task.completed.todone',
      begin: `^([ \\t]*)(\\+)(!?)(?:(-[1-5]|-+)(?=\\s))?([ \\t]*)${TITLE}`,
      beginCaptures: {
        2: { name: 'markup.inserted meta.state.completed.todone' },
        3: { name: 'meta.state.emergency.inherited.todone' },
        4: { name: 'meta.marker.completed.todone' },
        6: { name: 'markup.strikethrough meta.title.completed.todone' },
      },
      end: BLOCK_END,
      patterns: [{ include: '#finished-content' }],
    },

    // `.` marks a task as cancelled (ignored), optionally with a reason in
    // parentheses right before the title.
    'cancelled-task': {
      name: 'comment meta.task.cancelled.todone',
      begin:
        `^([ \\t]*)(\\.)(\\+?)(!?)(-[1-5]|-+)(?=\\s)([ \\t]*)` +
        `(?:(\\()([^)\\n]*)(\\)))?([ \\t]*)${TITLE}`,
      beginCaptures: {
        2: { name: 'markup.deleted meta.state.cancelled.todone' },
        3: { name: 'meta.state.completed.inherited.todone' },
        4: { name: 'meta.state.emergency.inherited.todone' },
        5: { name: 'meta.marker.cancelled.todone' },
        7: { name: 'emphasis markup.deleted punctuation.definition.reason.begin.todone' },
        8: { name: 'emphasis markup.deleted meta.reason.cancelled.todone' },
        9: { name: 'emphasis markup.deleted punctuation.definition.reason.end.todone' },
        11: { name: 'meta.title.cancelled.todone' },
      },
      end: BLOCK_END,
      patterns: [{ include: '#finished-content' }],
    },

    // Inside completed or cancelled blocks, nested tasks only get their marker
    // scoped so the whole subtree stays uniformly dim.
    'finished-content': {
      patterns: [
        {
          match: '^[ \\t]+([.+]*!?(?:-[1-5]|-+))(?=\\s)',
          captures: { 1: { name: 'meta.marker.inherited.todone' } },
        },
        { include: '#raw-note' },
      ],
    },

    ...Object.fromEntries(LEVELS.map((n) => [`emergency-task-${n}`, emergencyTask(n)])),
    ...Object.fromEntries(LEVELS.map((n) => [`task-${n}`, activeTask(n)])),

    // Inline notes (after `:`) and indented note lines.
    note: {
      name: 'comment meta.note.todone',
      begin: '(?=\\S)',
      end: '$',
      patterns: [{ include: '#emphasis' }, { include: '#raw-note' }],
    },

    // Text wrapped in backticks. The original only highlights it inside notes;
    // this port also highlights it inside active task titles.
    emphasis: {
      name: 'emphasis markup.inline.raw meta.emphasis.todone',
      begin: '`',
      beginCaptures: { 0: { name: 'punctuation.definition.emphasis.begin.todone' } },
      end: '`',
      endCaptures: { 0: { name: 'punctuation.definition.emphasis.end.todone' } },
      patterns: [{ match: '\\\\`' }],
    },

    // Raw note blocks between `///` markers. Lines inside are never tasks.
    'raw-note': {
      name: 'comment meta.note.raw.todone',
      begin: '///',
      beginCaptures: { 0: { name: 'punctuation.definition.raw.begin.todone' } },
      end: '///',
      endCaptures: { 0: { name: 'punctuation.definition.raw.end.todone' } },
      patterns: [{ include: '#emphasis' }],
    },
  },
};

function render() {
  return JSON.stringify(grammar, null, 2) + '\n';
}

const outFile = path.join(__dirname, '..', 'syntaxes', 'todone.tmLanguage.json');

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
    if (current.replace(/\r\n/g, '\n') !== render()) {
      console.error('syntaxes/todone.tmLanguage.json is out of date. Run `npm run grammar`.');
      process.exit(1);
    }
    console.log('Grammar is up to date.');
  } else {
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    fs.writeFileSync(outFile, render());
    console.log(`Wrote ${path.relative(process.cwd(), outFile)}`);
  }
}

module.exports = { render, outFile };
